#!/usr/bin/env python3
"""CPU Ollama deployments omit GPU placement, host checks, and Compose requests."""

from pathlib import Path

import yaml
from ansible.parsing.dataloader import DataLoader
from ansible.template import Templar


ROOT = Path(__file__).resolve().parents[1]


def read_yaml(path):
    return yaml.safe_load((ROOT / path).read_text(encoding="utf-8"))


def render(source, variables):
    return Templar(loader=DataLoader(), variables=variables).template(source)


def walk_tasks(value):
    if isinstance(value, dict):
        if "name" in value:
            yield value
        for child in value.values():
            yield from walk_tasks(child)
    elif isinstance(value, list):
        for child in value:
            yield from walk_tasks(child)


def test_compose_template_cpu_and_gpu_modes():
    template = (ROOT / "ansible/roles/ollama/templates/docker-compose.yml.j2").read_text(
        encoding="utf-8"
    )
    base = {
        "ansible_managed": "generated by test",
        "instance": "ollama",
        "app_config": {
            "app": {
                "image": "ollama/ollama:test",
                "port": 11434,
                "models_path": "/opt/ollama/models",
            }
        },
    }

    cpu = yaml.safe_load(render(template, {**base, "app_config": {
        "app": {**base["app_config"]["app"], "gpu_device": ""}
    }}))
    cpu_service = cpu["services"]["ollama"]
    assert "gpus" not in cpu_service
    assert "deploy" not in cpu_service
    assert cpu_service["volumes"] == [
        "/opt/ollama/models:/root/.ollama",
        "/etc/localtime:/etc/localtime:ro",
    ]

    gpu = yaml.safe_load(render(template, {**base, "app_config": {
        "app": {**base["app_config"]["app"], "gpu_device": "ollama-gpu"}
    }}))
    gpu_service = gpu["services"]["ollama"]
    assert gpu_service["gpus"] == "all"
    assert gpu_service["deploy"]["resources"]["reservations"]["devices"] == [
        {"driver": "nvidia", "count": "all", "capabilities": ["gpu"]}
    ]


def test_playbook_selects_cpu_or_dedicated_gpu_placement():
    playbook = read_yaml("ansible/playbooks/apps/ollama.yml")
    provision = playbook[0]
    placement_tasks = [
        task
        for task in walk_tasks(provision)
        if task.get("ansible.builtin.include_tasks", "").endswith(
            ("ensure-cloud-template.yml", "vm-clone.yml")
        )
    ]
    assert len(placement_tasks) == 2

    for task in placement_tasks:
        expression = task["vars"]["proxmox_placement_class"]
        assert (
            render(expression, {"app_config": {"app": {"gpu_device": ""}}}).strip()
            == "floating_vm"
        )
        assert (
            render(expression, {"app_config": {"app": {"gpu_device": "ollama-gpu"}}}).strip()
            == "gpu_vm"
        )
        device = task["vars"]["proxmox_placement_device"]
        assert render(device, {"app_config": {"app": {"gpu_device": ""}}}) == ""

    attach = next(
        task
        for task in walk_tasks(provision)
        if task.get("name") == "Attach the named Ollama PCI device"
    )
    cpu_context = {"app_config": {"app": {"gpu_device": ""}}}
    gpu_context = {"app_config": {"app": {"gpu_device": "ollama-gpu"}}}
    assert not render("{{ " + attach["when"] + " }}", cpu_context)
    assert render("{{ " + attach["when"] + " }}", gpu_context)

    contract = next(
        task for task in provision["pre_tasks"]
        if task.get("name") == "Assert the VM, optional PCI, and model-storage contract"
    )
    assert all("gpu_device" not in condition for condition in contract["ansible.builtin.assert"]["that"])


def test_gpu_health_checks_only_run_for_declared_gpu():
    tasks = read_yaml("ansible/roles/ollama/tasks/main.yml")
    gpu_tasks = [
        task
        for task in tasks
        if any(
            marker in task["name"]
            for marker in ("NVIDIA GPU", "NVIDIA runtime", "GPU is usable", "Container Toolkit")
        )
    ]
    assert len(gpu_tasks) == 4
    cpu_context = {"app_config": {"app": {"gpu_device": ""}}}
    gpu_context = {"app_config": {"app": {"gpu_device": "ollama-gpu"}}}
    assert all(not render("{{ " + task["when"] + " }}", cpu_context) for task in gpu_tasks)
    assert all(render("{{ " + task["when"] + " }}", gpu_context) for task in gpu_tasks)


def main():
    defaults = read_yaml("ansible/vars/app-defaults/ollama.yml")["ollama_defaults"]
    assert defaults["app"]["gpu_device"] == ""
    test_compose_template_cpu_and_gpu_modes()
    test_playbook_selects_cpu_or_dedicated_gpu_placement()
    test_gpu_health_checks_only_run_for_declared_gpu()
    print("Ollama CPU and dedicated-GPU deployment modes: OK")


if __name__ == "__main__":
    main()
