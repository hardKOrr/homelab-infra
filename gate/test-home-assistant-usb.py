#!/usr/bin/env python3
"""Check Home Assistant's optional USB mapping in provisioning and Compose."""

from pathlib import Path

import yaml
from ansible.parsing.dataloader import DataLoader
from ansible.template import Templar


ROOT = Path(__file__).resolve().parent.parent
PLAYBOOK = ROOT / "ansible/playbooks/apps/home-assistant.yml"
ROLE_TASKS = ROOT / "ansible/roles/home-assistant/tasks/main.yml"
COMPOSE_TEMPLATE = ROOT / "ansible/roles/home-assistant/templates/docker-compose.yml.j2"
USB_TASKS = ROOT / "ansible/tasks/proxmox/attach-usb-passthrough.yml"
INSTANCE_EXAMPLE = ROOT / "config.example/apps/home-assistant.example.yml"
REMOVE_PLAYBOOK = ROOT / "ansible/playbooks/apps/remove.yml"
MISSING = object()


def render(source, variables):
    return Templar(loader=DataLoader(), variables=variables).template(source)


def load_yaml(path):
    return list(yaml.safe_load_all(path.read_text()))


def task_named(tasks, name):
    return next(task for task in tasks if task.get("name") == name)


def find_task(node, name):
    if isinstance(node, dict):
        if node.get("name") == name:
            return node
        for value in node.values():
            try:
                return find_task(value, name)
            except StopIteration:
                pass
    elif isinstance(node, list):
        for value in node:
            try:
                return find_task(value, name)
            except StopIteration:
                pass
    raise StopIteration(name)


def condition_result(expression, variables):
    return render("{{ (%s) }}" % expression, variables)


def compose_service(mapping_marker=MISSING):
    app = {
        "image": "ghcr.io/home-assistant/home-assistant:stable",
        "port": 8123,
        "config_path": "/opt/home-assistant/config",
        "usb_device_path": "/dev/ttyUSB0",
    }
    if mapping_marker is not MISSING:
        app["usb_mapping"] = mapping_marker
    rendered = render(
        COMPOSE_TEMPLATE.read_text(),
        {
            "ansible_managed": "# generated by gate",
            "instance": "home-assistant",
            "app_config": {"app": app},
        },
    )
    document = yaml.safe_load(rendered)
    return document["services"]["homeassistant"]


def main():
    example = yaml.safe_load(INSTANCE_EXAMPLE.read_text())
    assert example["app"]["usb_mapping"] == ""
    for section in ("proxmox", "routing"):
        assert section not in example or isinstance(example[section], dict), (
            f"{section} must be omitted or a mapping so instance config preserves defaults"
        )

    plays = load_yaml(PLAYBOOK)[0]
    provision = next(play for play in plays if play["name"] == "Home Assistant | Provision")
    provision_assertion = task_named(
        provision["pre_tasks"], "Assert the explicit VM and optional USB contract"
    )["ansible.builtin.assert"]["that"]
    vm_contract = " ".join(provision_assertion)
    assert "app_config.hosting.method == 'docker'" in vm_contract
    assert "app_config.proxmox.vm is mapping" in vm_contract
    assert "app_config.app.usb_mapping | default('', true) | length == 0" in vm_contract

    optional_path_condition = provision_assertion[-1]
    assert condition_result(
        optional_path_condition,
        {"app_config": {"app": {"usb_mapping": "", "usb_device_path": "invalid"}}},
    ) is True
    assert condition_result(
        optional_path_condition,
        {"app_config": {"app": {"usb_mapping": None, "usb_device_path": "invalid"}}},
    ) is True
    assert condition_result(
        optional_path_condition,
        {
            "app_config": {
                "app": {"usb_mapping": "coordinator", "usb_device_path": "/dev/ttyUSB0"}
            }
        },
    ) is True
    assert condition_result(
        optional_path_condition,
        {"app_config": {"app": {"usb_mapping": "coordinator", "usb_device_path": "ttyUSB0"}}},
    ) is False

    attach = task_named(provision["tasks"], "Attach the optional Zigbee USB resource mapping")
    assert attach["ansible.builtin.include_tasks"] == "../../tasks/proxmox/attach-usb-passthrough.yml"
    assert condition_result(attach["when"], {"app_config": {"app": {"usb_mapping": ""}}}) is False
    null_mapping_vars = {"app_config": {"app": {"usb_mapping": None}}}
    assert condition_result(attach["when"], null_mapping_vars) is False
    assert condition_result(
        attach["when"], {"app_config": {"app": {"usb_mapping": "coordinator"}}}
    ) is True
    mapping_value = attach["vars"]["usb_passthrough_device"]["mapping"]
    assert render(mapping_value, null_mapping_vars) == ""

    role_tasks = load_yaml(ROLE_TASKS)[0]
    role_assertion = task_named(
        role_tasks, "Home Assistant | Assert the optional VM device contract reached the role"
    )["ansible.builtin.assert"]["that"]
    assert any("_ha_integration_credentials is mapping" in check for check in role_assertion)
    role_usb_condition = next(
        check for check in role_assertion if "usb_mapping" in check and "usb_device_path" in check
    )
    assert condition_result(
        role_usb_condition,
        {"app_config": {"app": {"usb_mapping": None, "usb_device_path": "invalid"}}},
    ) is True

    assert "devices" not in compose_service("")
    assert "devices" not in compose_service(None)
    assert "devices" not in compose_service()
    assert compose_service("coordinator")["devices"] == [
        "/dev/ttyUSB0:/dev/ttyUSB0"
    ]

    remove_tasks = load_yaml(REMOVE_PLAYBOOK)
    detach = find_task(remove_tasks, "Detach Home Assistant's project-owned Zigbee USB mapping")
    assert detach["ansible.builtin.include_tasks"] == "../../tasks/proxmox/detach-usb-passthrough.yml"
    remove_null_mapping = {
        "remove_kind": "docker",
        "remove_app": "home-assistant",
        "instance": "home-assistant",
        "app_config": {"app": {"usb_mapping": None}},
    }
    assert condition_result(detach["when"][-1], remove_null_mapping) is False
    assert render(detach["vars"]["usb_passthrough_device"]["mapping"], remove_null_mapping) == ""

    usb_tasks = load_yaml(USB_TASKS)[0]
    required_input = task_named(usb_tasks, "USB passthrough | Assert required input")
    assert "usb_passthrough_device.mapping | length > 0" in " ".join(
        required_input["ansible.builtin.assert"]["that"]
    )
    assert "vendorid:productid pair" in required_input["ansible.builtin.assert"]["fail_msg"]
    dedicated = task_named(
        usb_tasks, "USB passthrough | Assert the physical device is declared dedicated"
    )["ansible.builtin.assert"]["that"]
    assert any("== 'dedicated'" in check for check in dedicated)
    assert any("== 'usb'" in check for check in dedicated)
    mapping_lookup = task_named(usb_tasks, "USB passthrough | Verify the mapping exists on the cluster")
    assert "/cluster/mapping/usb/{{ usb_passthrough_device.mapping }}" in mapping_lookup[
        "ansible.builtin.command"
    ]["cmd"]
    ownership = task_named(
        usb_tasks, "USB passthrough | Assert the guest carries the ownership tag"
    )["ansible.builtin.assert"]["that"]
    assert "'_+lab' in _usb_tags" in ownership
    conflict = task_named(
        usb_tasks,
        "USB passthrough | Assert the device is free, or already held by this guest",
    )["ansible.builtin.assert"]["that"]
    assert "(_usb_holders | length == 0) or (_usb_holders == [_usb_vmid])" in conflict

    print("Home Assistant USB: empty mappings omit passthrough; configured mappings retain validation and binding")


if __name__ == "__main__":
    main()
